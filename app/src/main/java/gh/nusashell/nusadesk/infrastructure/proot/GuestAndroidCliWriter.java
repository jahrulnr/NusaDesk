package gh.nusashell.nusadesk.infrastructure.proot;

/**
 * Guest-side native Android tool dispatcher (ADR-0045).
 *
 * <p>The host binds the device's Android tool trees into the guest at their
 * identical paths ({@code /system/bin}, {@code /system/lib64}), so the
 * device's own binaries — mksh at {@code /system/bin/sh}, the
 * {@code toolbox} and {@code toybox} multicall binaries, and on a rooted
 * device {@code /system/bin/su} — run natively under the app's own uid.
 * This writer installs {@code /usr/local/bin/android-cli}, the single
 * dispatcher over that tree:</p>
 *
 * <ul>
 *   <li>{@code android-cli sh [args…]}, {@code getprop [name]},
 *       {@code toolbox <applet> [args…]} and
 *       {@code toybox <applet> [args…]} exec the matching
 *       {@code <root>/bin/} binary with the caller's argument list;</li>
 *   <li>{@code android-cli exec <absolute-path> [args…]} runs any binary
 *       under the bound trees — no verb allowlist: the platform's own
 *       uid/permission checks are the boundary, and a denial is passed
 *       through verbatim followed by one {@code android-cli: hint:} line;</li>
 *   <li>{@code android-cli su [args…]} runs the device's own
 *       {@code /system/bin/su} when present — the documented door to the
 *       root tier, one Magisk prompt per grant — and fails typed (exit 5)
 *       with a not-rooted hint when it is absent;</li>
 *   <li>{@code android-cli permissions} is the one bridge-backed verb:
 *       it asks the capability bridge's {@code bridge.permissions}
 *       method — through the shared {@code termux_compat} runtime
 *       module — for the manifest-declared grant states and prints one
 *       line per permission plus the Settings action that opens a
 *       missing grant. A dead bridge (no session env, a refused socket,
 *       an absent module) is an honest typed exit, never a guessed
 *       state;</li>
 *   <li>{@code doctor} probes the tree (each core tool gets a one-line
 *       exec probe, device su is reported {@code present|absent}), adds
 *       a bridge permission summary after the tier line, and prints the
 *       resulting tier plus the boundary note;
 *       {@code status} prints the tier as one machine line.</li>
 * </ul>
 *
 * <p>There is deliberately no adb in this version: power comes from the
 * binaries themselves, not from a loopback daemon or a tcpip step. The
 * script never builds a shell string out of user arguments — child argv is
 * always a list — prints one
 * {@code android-cli: tier=… source=native device=…} informational line to
 * stderr (suppressed by {@code -q} or {@code ANDROID_CLI_QUIET=1}) so stdout
 * stays pipeable, propagates the child's own exit code, and answers a
 * missing tool with a typed exit 5 naming the path it probed.
 * {@code ANDROID_CLI_SYSTEM_ROOT} relocates the {@code /system} tree, which
 * exists so hermetic tests can point at a temp tree of fake binaries;
 * {@code ANDROID_CLI_MODULE_DIR} and {@code ANDROID_CLI_ENV_FILE} do the
 * same for the {@code termux_compat} module directory and the bridge
 * session env path. Like
 * every generated guest file it is rewritten by
 * {@link GuestAwarenessReadmeWriter#ensure} on session start, so an app
 * update replaces a stale copy.</p>
 */
public final class GuestAndroidCliWriter {

    /** Guest-relative CLI path, executable on PATH. */
    public static final String GUEST_CLI_RELATIVE_PATH = "usr/local/bin/android-cli";
    /** CLI file name inside the fixed bin parent. */
    public static final String CLI_FILE_NAME = "android-cli";

    private GuestAndroidCliWriter() {
    }

    /**
     * The exact executable Python 3 script installed at
     * {@link #GUEST_CLI_RELATIVE_PATH}. Public so tests and documentation
     * tooling can pin the generated text.
     *
     * @param appVersion app version stamped into the script header
     */
    public static String scriptContent(String appVersion) {
        String version = GuestAwarenessReadmeWriter.requireVersionForWriter(appVersion);
        return String.join("\n",
                "#!/usr/bin/env python3",
                "# NusaDesk native Android tool dispatcher - generated by the",
                "# NusaDesk Android app. App version: " + version,
                "# Runs the device's own binaries natively inside the guest: the",
                "# host binds the Android tool trees at their identical paths, so",
                "# <root>/bin/sh, <root>/bin/toolbox and <root>/bin/toybox are the",
                "# phone's own tools run under the app's uid. There is no adb and",
                "# no tcpip step: the platform's own uid checks are the boundary",
                "# and a denial is passed through verbatim. Child argv is always",
                "# a list - never a shell string.",
                "# The permissions verb is the one bridge-backed path: it asks",
                "# the capability bridge for the declared grant states through",
                "# the shared termux_compat module and reports an unreachable",
                "# bridge honestly - never a guessed state.",
                "",
                "import os",
                "import subprocess",
                "import sys",
                "",
                "SYSTEM_ROOT = os.environ.get('ANDROID_CLI_SYSTEM_ROOT') or '/system'",
                "# The env-file and module-dir overrides exist for hermetic tests",
                "# only, like ANDROID_CLI_SYSTEM_ROOT; the device defaults are the",
                "# real session paths.",
                "ENV_FILE = (os.environ.get('ANDROID_CLI_ENV_FILE')",
                "            or '" + GuestAwarenessReadmeWriter.GUEST_ENV_FILE_PATH + "')",
                "MODULE_DIR = (os.environ.get('ANDROID_CLI_MODULE_DIR')",
                "              or '" + GuestTermuxCompatWriter.GUEST_MODULE_DIR + "')",
                "PROBE_TIMEOUT_SECONDS = 10.0",
                "CORE_TOOLS = ('sh', 'toolbox', 'toybox')",
                "PERMISSION_STATES = ('granted', 'required', 'denied', 'unsupported')",
                "USAGE = ('usage: android-cli [-q] doctor'",
                "         + ' | status'",
                "         + ' | permissions'",
                "         + ' | sh [args...]'",
                "         + ' | getprop [name]'",
                "         + ' | toolbox <applet> [args...]'",
                "         + ' | toybox <applet> [args...]'",
                "         + ' | su [args...]'",
                "         + ' | exec <absolute-path> [args...]')",
                "",
                "",
                "def quiet_env():",
                "    return os.environ.get('ANDROID_CLI_QUIET') == '1'",
                "",
                "",
                "ANDROID_BIN_PATHS = ['/system/bin', '/system/xbin', '/product/bin',",
                "                     '/apex/com.android.runtime/bin']",
                "ANDROID_LIB_PATHS = ['/apex/com.android.runtime/lib64/bionic',",
                "                     '/apex/com.android.art/lib64',",
                "                     '/apex/com.android.i18n/lib64',",
                "                     '/system/lib64']",
                "",
                "",
                "def child_env():",
                "    # Android's own search paths for the children only, so script-based",
                "    # tools find cmd/app_process and ABI libraries live where the",
                "    # linker expects them (the app cannot read /linkerconfig, so the",
                "    # linker has no namespace map of its own here). The session PATH",
                "    # is never touched, and the platform's checks remain the boundary.",
                "    env = dict(os.environ)",
                "    env['PATH'] = ':'.join(ANDROID_BIN_PATHS",
                "                           + ([env['PATH']] if env.get('PATH') else []))",
                "    env['LD_LIBRARY_PATH'] = ':'.join(",
                "        ANDROID_LIB_PATHS",
                "        + ([env['LD_LIBRARY_PATH']] if env.get('LD_LIBRARY_PATH') else []))",
                "    return env",
                "",
                "",
                "def info(tier, quiet, source='native'):",
                "    if not quiet:",
                "        print('android-cli: tier=' + tier + ' source=' + source",
                "              + ' device=' + SYSTEM_ROOT, file=sys.stderr)",
                "",
                "",
                "def tool_path(name):",
                "    return os.path.join(SYSTEM_ROOT, 'bin', name)",
                "",
                "",
                "def present(path):",
                "    # Follows links on purpose: getprop -> toolbox counts when the",
                "    # toolbox binary it points at is there.",
                "    return os.path.isfile(path)",
                "",
                "",
                "def tier_now():",
                "    for name in CORE_TOOLS:",
                "        if present(tool_path(name)):",
                "            return 'app'",
                "    return 'none'",
                "",
                "",
                "def hint():",
                "    print('android-cli: hint: the platform denied this to the app uid;'",
                "          + ' this device grants more only to a higher tier - run'",
                "          + ' android-cli doctor', file=sys.stderr)",
                "",
                "",
                "def missing(path):",
                "    print('android-cli: ' + path + ': no such tool under'",
                "          + ' ANDROID_CLI_SYSTEM_ROOT (' + SYSTEM_ROOT + ')',",
                "          file=sys.stderr)",
                "    return 5",
                "",
                "",
                "def run_child(path, args):",
                "    try:",
                "        completed = subprocess.run([path] + list(args), env=child_env())",
                "    except FileNotFoundError:",
                "        return missing(path)",
                "    except OSError as error:",
                "        print('android-cli: ' + path + ': ' + str(error),",
                "              file=sys.stderr)",
                "        return 1",
                "    if completed.returncode != 0:",
                "        hint()",
                "    return completed.returncode",
                "",
                "",
                "def cmd_tool(name, args):",
                "    path = tool_path(name)",
                "    if not present(path):",
                "        return missing(path)",
                "    return run_child(path, args)",
                "",
                "",
                "def cmd_su(args):",
                "    path = tool_path('su')",
                "    if not present(path):",
                "        print('android-cli: ' + path + ': device su absent - the'",
                "              + ' device is not rooted, or su is not under the'",
                "              + ' bound trees; android-cli doctor shows what exists',",
                "              file=sys.stderr)",
                "        return 5",
                "    return run_child(path, args)",
                "",
                "",
                "def cmd_exec(args):",
                "    target = args[0]",
                "    if not target.startswith('/'):",
                "        print('android-cli: exec needs an absolute path under'",
                "              + ' ANDROID_CLI_SYSTEM_ROOT (' + SYSTEM_ROOT + ')',",
                "              file=sys.stderr)",
                "        return 2",
                "    normalized = os.path.normpath(target)",
                "    root = os.path.normpath(SYSTEM_ROOT)",
                "    prefix = root if root.endswith(os.sep) else root + os.sep",
                "    if normalized != root and not normalized.startswith(prefix):",
                "        print('android-cli: ' + normalized + ' is not under'",
                "              + ' ANDROID_CLI_SYSTEM_ROOT (' + root + ')',",
                "              file=sys.stderr)",
                "        return 2",
                "    if not present(normalized):",
                "        return missing(normalized)",
                "    return run_child(normalized, args[1:])",
                "",
                "",
                "def probe(argv):",
                "    try:",
                "        completed = subprocess.run(",
                "            argv, env=child_env(), stdout=subprocess.PIPE,",
                "            stderr=subprocess.STDOUT,",
                "            timeout=PROBE_TIMEOUT_SECONDS)",
                "    except (OSError, subprocess.SubprocessError):",
                "        return False, ''",
                "    output = completed.stdout or b''",
                "    return True, output.decode('utf-8', 'replace')",
                "",
                "",
                "def bridge_runtime():",
                "    # The shared Termux-compat module owns the bridge transport",
                "    # (session env, token, the socket protocol). The import is lazy",
                "    # so the native verbs still work where the layer is absent;",
                "    # only the bridge-backed verbs fail typed when it is missing.",
                "    if MODULE_DIR not in sys.path:",
                "        sys.path.insert(0, MODULE_DIR)",
                "    try:",
                "        import termux_compat",
                "    except ImportError:",
                "        return None",
                "    return termux_compat",
                "",
                "",
                "def parse_permissions(response):",
                "    # bridge.permissions answers 'permissions' as a comma list of",
                "    # name:state entries and 'hints' as name=<settings action>",
                "    # entries for every grant that is not granted. A shape",
                "    # violation raises, so the caller reports a malformed answer",
                "    # instead of guessing a state.",
                "    raw = response.get('permissions')",
                "    if not isinstance(raw, str):",
                "        raise ValueError('permissions field missing')",
                "    states = []",
                "    for entry in raw.split(','):",
                "        if not entry:",
                "            continue",
                "        name, sep, state = entry.partition(':')",
                "        if not sep or state not in PERMISSION_STATES:",
                "            raise ValueError('bad permission entry')",
                "        states.append((name, state))",
                "    hints = {}",
                "    raw_hints = response.get('hints')",
                "    if isinstance(raw_hints, str):",
                "        for entry in raw_hints.split(','):",
                "            name, sep, action = entry.partition('=')",
                "            if sep and name and action:",
                "                hints[name] = action",
                "    return states, hints",
                "",
                "",
                "def permission_counts(states):",
                "    counts = {'granted': 0, 'required': 0, 'denied': 0,",
                "              'unsupported': 0}",
                "    for _name, state in states:",
                "        counts[state] += 1",
                "    return counts",
                "",
                "",
                "def count_text(counts):",
                "    return (str(counts['granted']) + ' granted, '",
                "            + str(counts['required']) + ' required, '",
                "            + str(counts['denied']) + ' denied, '",
                "            + str(counts['unsupported']) + ' unsupported')",
                "",
                "",
                "def cmd_permissions():",
                "    tc = bridge_runtime()",
                "    if tc is None:",
                "        print('android-cli: ' + MODULE_DIR + '/termux_compat.py:'",
                "              + ' the shared bridge runtime is not installed -'",
                "              + ' permission states unknown', file=sys.stderr)",
                "        return 5",
                "    try:",
                "        response = tc.bridge_call('bridge.permissions')",
                "    except tc.BridgeError as error:",
                "        print('android-cli: bridge.permissions: ' + str(error),",
                "              file=sys.stderr)",
                "        return 1",
                "    except (tc.CliError, OSError) as error:",
                "        print('android-cli: the capability bridge is not'",
                "              + ' reachable (' + str(error) + ') - permission'",
                "              + ' states unknown; the bridge lives with the'",
                "              + ' NusaDesk session', file=sys.stderr)",
                "        return 5",
                "    try:",
                "        states, hints = parse_permissions(response)",
                "    except (ValueError, TypeError, KeyError):",
                "        print('android-cli: malformed bridge response -'",
                "              + ' permission states unknown', file=sys.stderr)",
                "        return 5",
                "    print('android-cli permissions - declared Android grants')",
                "    for name, state in states:",
                "        line = name + ': ' + state",
                "        action = hints.get(name)",
                "        if state != 'granted' and action:",
                "            line += '  settings: ' + action",
                "        print(line)",
                "    counts = permission_counts(states)",
                "    print('summary: ' + count_text(counts))",
                "    if counts['required'] or counts['denied']:",
                "        print(\"a required grant can still be asked - the\"",
                "              + \" bridge's permission.request runs the runtime\"",
                "              + ' prompt, or the Settings screen above in settings'",
                "              + \" mode, through the app's foreground Activity\")",
                "    return 0",
                "",
                "",
                "def doctor_permissions():",
                "    if not os.path.isfile(ENV_FILE):",
                "        print('permissions (bridge): no session env - grant'",
                "              + ' states unknown')",
                "        return",
                "    tc = bridge_runtime()",
                "    if tc is None:",
                "        print('permissions (bridge): shared runtime module'",
                "              + ' absent - grant states unknown')",
                "        return",
                "    try:",
                "        states, _hints = parse_permissions(",
                "            tc.bridge_call('bridge.permissions'))",
                "    except (tc.BridgeError, tc.CliError, OSError,",
                "            ValueError, TypeError, KeyError):",
                "        print('permissions (bridge): unreachable - grant'",
                "              + ' states unknown')",
                "        return",
                "    counts = permission_counts(states)",
                "    print('permissions (bridge): ' + count_text(counts))",
                "    if counts['required'] or counts['denied']:",
                "        print(\"  open the rest: android-cli permissions lists\"",
                "              + \" each grant's Settings action; a termux-* command\"",
                "              + ' that needs a grant names it on use; the bridge'",
                "              + ' permission.request asks for a runtime grant'",
                "              + \" through the app's foreground Activity\")",
                "",
                "",
                "def cmd_doctor():",
                "    print('android-cli doctor - native Android tools')",
                "    print('system root: ' + SYSTEM_ROOT",
                "          + ' (ANDROID_CLI_SYSTEM_ROOT)')",
                "    if not os.path.isdir(SYSTEM_ROOT):",
                "        print('system tree: missing - the host bound no Android'",
                "              + ' tool tree')",
                "    tier = 'none'",
                "    for name in CORE_TOOLS:",
                "        path = tool_path(name)",
                "        if not present(path):",
                "            print(name + ': missing (' + path + ')')",
                "            continue",
                "        if name == 'sh':",
                "            ran, output = probe([path, '-c', 'echo android-cli-probe'])",
                "            ok = ran and 'android-cli-probe' in output",
                "        else:",
                "            ran, _output = probe([path])",
                "            ok = ran",
                "        print(name + ': '",
                "              + ('present, exec ok' if ok else 'present, exec failed')",
                "              + ' (' + path + ')')",
                "        if ok:",
                "            tier = 'app'",
                "    for name in ('getprop', 'su'):",
                "        path = tool_path(name)",
                "        label = 'device su' if name == 'su' else name",
                "        print(label + ': ' + ('present' if present(path) else 'absent')",
                "              + ' (' + path + ')')",
                "    print('bridge session env: '",
                "          + ('present' if os.path.isfile(ENV_FILE) else 'absent')",
                "          + ' (informational only)')",
                "    print('tier: ' + tier + ' source=native')",
                "    doctor_permissions()",
                "    print(\"note: privileged verbs (screencap, input, pm, am,\"",
                "          + \" dumpsys) are denied to an app uid by the platform's\"",
                "          + \" own checks - they fail verbatim and no flag changes\"",
                "          + \" that. A shell tier is a separate, documented enablement\"",
                "          + \" (the device's own adbd over loopback), not part of v1.\"",
                "          + \" On a rooted device android-cli su is the user's own door\"",
                "          + \" to a root shell: one Magisk prompt per grant.\")",
                "    return 0 if tier == 'app' else 5",
                "",
                "",
                "def cmd_status():",
                "    print('tier=' + tier_now() + ' source=native')",
                "    return 0",
                "",
                "",
                "def usage_error():",
                "    print('android-cli: ' + USAGE, file=sys.stderr)",
                "    return 2",
                "",
                "",
                "def main(argv):",
                "    args = list(argv)",
                "    quiet = quiet_env()",
                "    while args and args[0] in ('-q', '--quiet'):",
                "        args = args[1:]",
                "        quiet = True",
                "    if args and args[0] in ('-h', '--help'):",
                "        print(USAGE)",
                "        return 0",
                "    if not args:",
                "        return usage_error()",
                "    verb, rest = args[0], args[1:]",
                "    if verb == 'doctor':",
                "        if rest:",
                "            return usage_error()",
                "        info(tier_now(), quiet)",
                "        return cmd_doctor()",
                "    if verb == 'status':",
                "        if rest:",
                "            return usage_error()",
                "        info(tier_now(), quiet)",
                "        return cmd_status()",
                "    if verb == 'permissions':",
                "        if rest:",
                "            return usage_error()",
                "        info(tier_now(), quiet, 'bridge')",
                "        return cmd_permissions()",
                "    if verb == 'sh':",
                "        info(tier_now(), quiet)",
                "        return cmd_tool('sh', rest)",
                "    if verb == 'getprop':",
                "        if len(rest) > 1:",
                "            return usage_error()",
                "        info(tier_now(), quiet)",
                "        return cmd_tool('getprop', rest)",
                "    if verb in ('toolbox', 'toybox'):",
                "        if not rest:",
                "            return usage_error()",
                "        info(tier_now(), quiet)",
                "        return cmd_tool(verb, rest)",
                "    if verb == 'su':",
                "        info(tier_now(), quiet)",
                "        return cmd_su(rest)",
                "    if verb == 'exec':",
                "        if not rest:",
                "            return usage_error()",
                "        info(tier_now(), quiet)",
                "        return cmd_exec(rest)",
                "    return usage_error()",
                "",
                "",
                "if __name__ == '__main__':",
                "    sys.exit(main(sys.argv[1:]))",
                "") + "\n";
    }
}
