package gh.nusashell.nusadesk.infrastructure.proot;

/**
 * Guest-side USB driver daemon.
 *
 * <p>The stock Ubuntu {@code adb} in the guest talks to USB through libusb,
 * and the guest has no USB bus of its own. {@code nusadesk-usbd} is the
 * piece that bridges the two: it owns every opened device descriptor for the
 * session (through the Android capability bridge's {@code usb.list} /
 * {@code usb.open}), caches each device's descriptor as soon as one is
 * opened, and serves the {@code libusb-shim} loaded into adb over the
 * abstract unix socket {@code nusadesk-usbd}:</p>
 *
 * <ul>
 *   <li>{@code LIST} answers with one {@code DEV …} line per attached device
 *       (with the cached descriptor fields when available) and a final
 *       {@code END};</li>
 *   <li>{@code OPEN <vid> <pid>} returns {@code OK …} together with the
 *       device descriptor passed with {@code SCM_RIGHTS}, or {@code ERR
 *       <code>} with the bridge's typed error;</li>
 *   <li>{@code PING} answers {@code PONG}.</li>
 * </ul>
 *
 * <p>Requests are handled on per-connection threads because an {@code OPEN}
 * can block on the host's USB permission dialog; the daemon keeps its own
 * reference to every descriptor it opened, so a client closing its copy
 * never tears the device down mid-session. {@code --ensure} starts the
 * daemon detached when it is not already listening, which is what the
 * generated {@code adb} wrapper calls before every adb invocation.</p>
 */
public final class GuestUsbDaemonWriter {

    /** Guest-relative daemon path, executable on PATH. */
    public static final String GUEST_DAEMON_RELATIVE_PATH = "usr/local/bin/nusadesk-usbd";
    /** Daemon file name inside the fixed bin parent. */
    public static final String DAEMON_FILE_NAME = "nusadesk-usbd";

    private GuestUsbDaemonWriter() {
    }

    /**
     * The exact executable Python 3 script installed at
     * {@link #GUEST_DAEMON_RELATIVE_PATH}.
     *
     * @param appVersion app version stamped into the script header
     */
    public static String scriptContent(String appVersion) {
        String version = GuestAwarenessReadmeWriter.requireVersionForWriter(appVersion);
        return String.join("\n",
                "#!/usr/bin/env python3",
                "# NusaDesk USB driver daemon - generated by the NusaDesk Android",
                "# app. App version: " + version,
                "# Fixed session env: " + GuestAwarenessReadmeWriter.GUEST_ENV_FILE_PATH,
                "# Serves the libusb shim over the abstract unix socket",
                "# 'nusadesk-usbd': LIST -> DEV lines + END; OPEN <vid> <pid> ->",
                "# OK + fd (SCM_RIGHTS) or ERR <code>; PING -> PONG.",
                "# The daemon owns every opened device fd for the session.",
                "",
                "import array",
                "import ctypes",
                "import json",
                "import os",
                "import socket",
                "import struct",
                "import sys",
                "import threading",
                "import time",
                "",
                "ENV_FILE = '" + GuestAwarenessReadmeWriter.GUEST_ENV_FILE_PATH + "'",
                "SOCKET_NAME = 'nusadesk-usbd'",
                "SOCKET_PREFIX = 'nu-usb-'",
                "PROTOCOL_VERSION = 1",
                "BRIDGE_TIMEOUT_SECONDS = 15.0",
                "# usb.open can block inside the app while the USB permission",
                "# dialog is up, so it gets a wider timeout than a plain query.",
                "USB_OPEN_TIMEOUT_SECONDS = 75.0",
                "LISTEN_TIMEOUT_SECONDS = 60.0",
                "MAX_REQUEST_BYTES = 256",
                "MAX_CONFIG_LINE_BYTES = 1024",
                "MAX_RESPONSE_BYTES = 16384",
                "ENV_ADDRESS = 'NUSADESK_ANDROID_BRIDGE_ADDRESS'",
                "ENV_PORT = 'NUSADESK_ANDROID_BRIDGE_PORT'",
                "ENV_TOKEN = 'NUSADESK_ANDROID_BRIDGE_TOKEN'",
                "ENV_PROTOCOL = 'NUSADESK_ANDROID_BRIDGE_PROTOCOL'",
                "TOKEN_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-'",
                "USBDEVFS_CONTROL = 0xC0185500",
                "DESCRIPTOR_SIZE = 18",
                "CONTROL_TIMEOUT_MS = 2000",
                "",
                "",
                "class CliError(Exception):",
                "    pass",
                "",
                "",
                "class BridgeError(Exception):",
                "    pass",
                "",
                "",
                "class UsbdevfsCtrlTransfer(ctypes.Structure):",
                "    _fields_ = [('bRequestType', ctypes.c_ubyte),",
                "                ('bRequest', ctypes.c_ubyte),",
                "                ('wValue', ctypes.c_ushort),",
                "                ('wIndex', ctypes.c_ushort),",
                "                ('wLength', ctypes.c_ushort),",
                "                ('timeout', ctypes.c_uint),",
                "                ('data', ctypes.c_void_p)]",
                "",
                "",
                "_descriptor_cache = {}",
                "",
                "",
                "def load_config(path):",
                "    values = {}",
                "    try:",
                "        with open(path, 'r', encoding='ascii') as handle:",
                "            for raw in handle:",
                "                if len(raw) > MAX_CONFIG_LINE_BYTES:",
                "                    raise CliError('session env line too long')",
                "                line = raw.strip()",
                "                if not line or line.startswith('#'):",
                "                    continue",
                "                if '=' not in line:",
                "                    raise CliError('malformed session env line')",
                "                key, _, value = line.partition('=')",
                "                key = key.strip()",
                "                value = value.strip()",
                "                if key not in (ENV_ADDRESS, ENV_PORT, ENV_TOKEN,",
                "                                ENV_PROTOCOL):",
                "                    raise CliError('unexpected session env key')",
                "                if key in values:",
                "                    raise CliError('duplicate session env key')",
                "                values[key] = value",
                "    except (IOError, UnicodeDecodeError, CliError) as error:",
                "        if isinstance(error, CliError):",
                "            raise",
                "        raise CliError('cannot read session env')",
                "    address = values.get(ENV_ADDRESS)",
                "    port_text = values.get(ENV_PORT)",
                "    token = values.get(ENV_TOKEN)",
                "    protocol = values.get(ENV_PROTOCOL)",
                "    if address != '127.0.0.1':",
                "        raise CliError('bridge address must be loopback only')",
                "    if protocol != str(PROTOCOL_VERSION):",
                "        raise CliError('unsupported bridge protocol version')",
                "    try:",
                "        port = int(port_text, 10)",
                "    except (TypeError, ValueError):",
                "        raise CliError('invalid session env port')",
                "    if port < 1 or port > 65535:",
                "        raise CliError('invalid session env port')",
                "    if token is None or len(token) < 16 or len(token) > 256:",
                "        raise CliError('invalid session env token')",
                "    if any(ch not in TOKEN_ALPHABET for ch in token):",
                "        raise CliError('invalid session env token')",
                "    return address, port, token",
                "",
                "",
                "def bridge_call(method, params, timeout):",
                "    address, port, token = load_config(ENV_FILE)",
                "    request = {'v': PROTOCOL_VERSION,",
                "               'id': os.urandom(8).hex(),",
                "               'token': token,",
                "               'method': method}",
                "    if params is not None:",
                "        request['params'] = params",
                "    payload = json.dumps(request, separators=(',', ':'),",
                "                         ensure_ascii=True)",
                "    with socket.create_connection((address, port),",
                "                                  timeout=timeout) as sock:",
                "        sock.settimeout(timeout)",
                "        sock.sendall(payload.encode('ascii') + bytes([10]))",
                "        outgoing = bytearray()",
                "        while True:",
                "            chunk = sock.recv(4096)",
                "            if not chunk:",
                "                break",
                "            outgoing.extend(chunk)",
                "            if 10 in outgoing:",
                "                break",
                "            if len(outgoing) > MAX_RESPONSE_BYTES:",
                "                raise CliError('response too large')",
                "    if not outgoing:",
                "        raise CliError('empty bridge response')",
                "    line = outgoing.split(bytes([10]), 1)[0]",
                "    try:",
                "        parsed = json.loads(line.decode('utf-8'))",
                "    except ValueError:",
                "        raise CliError('bridge response is not JSON')",
                "    if not isinstance(parsed, dict):",
                "        raise CliError('bridge response is not a JSON object')",
                "    if parsed.get('v') != PROTOCOL_VERSION:",
                "        raise CliError('unsupported bridge response version')",
                "    if not parsed.get('ok'):",
                "        raise BridgeError(str(parsed.get('error', 'bridge error')))",
                "    return parsed",
                "",
                "",
                "def receive_fd(connection):",
                "    fds = array.array('i')",
                "    _msg, ancdata, _flags, _addr = connection.recvmsg(",
                "        4096, socket.CMSG_SPACE(fds.itemsize))",
                "    for level, ctype, cdata in ancdata:",
                "        if level == socket.SOL_SOCKET and ctype == socket.SCM_RIGHTS:",
                "            usable = len(cdata) - (len(cdata) % fds.itemsize)",
                "            fds.frombytes(cdata[:usable])",
                "    if not fds:",
                "        raise CliError('bridge sent no device fd')",
                "    return fds[0]",
                "",
                "",
                "def read_descriptor(fd):",
                "    payload = ctypes.create_string_buffer(DESCRIPTOR_SIZE)",
                "    transfer = UsbdevfsCtrlTransfer(",
                "        0x80, 6, 0x0100, 0, DESCRIPTOR_SIZE, CONTROL_TIMEOUT_MS,",
                "        ctypes.addressof(payload))",
                "    result = ctypes.CDLL(None, use_errno=True).ioctl(",
                "        fd, USBDEVFS_CONTROL, ctypes.byref(transfer))",
                "    if result < 0:",
                "        raise CliError('USBDEVFS_CONTROL failed')",
                "    raw = payload.raw",
                "    return {",
                "        'bcd_usb': struct.unpack_from('<H', raw, 2)[0],",
                "        'device_class': raw[4],",
                "        'sub_class': raw[5],",
                "        'protocol': raw[6],",
                "        'max_packet0': raw[7],",
                "        'i_manufacturer': raw[14],",
                "        'i_product': raw[15],",
                "        'i_serial': raw[16],",
                "        'num_configs': raw[17],",
                "    }",
                "",
                "",
                "def parse_device_id(text):",
                "    parts = text.split(':')",
                "    if len(parts) != 2:",
                "        raise CliError('bad device id')",
                "    pair = []",
                "    for part in parts:",
                "        try:",
                "            value = int(part, 16)",
                "        except ValueError:",
                "            raise CliError('bad device id')",
                "        if value < 0 or value > 0xffff:",
                "            raise CliError('bad device id')",
                "        pair.append(value)",
                "    return pair",
                "",
                "",
                "def open_device(vendor_id, product_id):",
                "    name = SOCKET_PREFIX + os.urandom(6).hex()",
                "    listener = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)",
                "    try:",
                "        listener.bind('\\0' + name)",
                "        listener.listen(1)",
                "        listener.settimeout(LISTEN_TIMEOUT_SECONDS)",
                "        bridge_call('usb.open', {'vendorId': vendor_id,",
                "                                 'productId': product_id,",
                "                                 'socket': name},",
                "                    USB_OPEN_TIMEOUT_SECONDS)",
                "        connection, _ = listener.accept()",
                "        connection.settimeout(LISTEN_TIMEOUT_SECONDS)",
                "    finally:",
                "        listener.close()",
                "    try:",
                "        return receive_fd(connection)",
                "    finally:",
                "        connection.close()",
                "",
                "",
                "def device_fd(vendor_id, product_id):",
                "    # Open the device for this request. Descriptors are cached,",
                "    # fds are not: a usbfs claim lives on the opened file, and the",
                "    # app replaces its previous connection on every usb.open, so a",
                "    # fresh descriptor is what lets the next client claim the",
                "    # interface cleanly instead of colliding with a stale claim.",
                "    key = '%04x:%04x' % (vendor_id, product_id)",
                "    fd = open_device(vendor_id, product_id)",
                "    try:",
                "        _descriptor_cache[key] = read_descriptor(fd)",
                "    except (CliError, OSError):",
                "        pass",
                "    return fd",
                "",
                "",
                "def device_line(device):",
                "    vendor_id = device['vendorId']",
                "    product_id = device['productId']",
                "    key = '%04x:%04x' % (vendor_id, product_id)",
                "    info = _descriptor_cache.get(key)",
                "    if not info:",
                "        return 'DEV %04x %04x' % (vendor_id, product_id)",
                "    return ('DEV %04x %04x %04x %02x %02x %02x %02x %02x %02x %02x %02x'",
                "            % (vendor_id, product_id, info['bcd_usb'],",
                "               info['device_class'], info['sub_class'], info['protocol'],",
                "               info['max_packet0'], info['i_manufacturer'],",
                "               info['i_product'], info['i_serial'], info['num_configs']))",
                "",
                "",
                "def is_adb_device(device):",
                "    interfaces = device.get('interfaces')",
                "    if not isinstance(interfaces, str) or not interfaces:",
                "        return True",
                "    return 'ff4201' in interfaces.split(',')",
                "",
                "",
                "def handle_list(connection):",
                "    parsed = bridge_call('usb.list', None, BRIDGE_TIMEOUT_SECONDS)",
                "    rows = parsed.get('devices')",
                "    if not isinstance(rows, str):",
                "        raise BridgeError('malformed-device-list')",
                "    devices = json.loads(rows)",
                "    if not isinstance(devices, list):",
                "        raise BridgeError('malformed-device-list')",
                "    lines = [device_line(device) for device in devices",
                "             if is_adb_device(device)]",
                "    lines.append('END')",
                "    connection.sendall(('\\n'.join(lines) + '\\n').encode('ascii'))",
                "",
                "",
                "def handle_open(connection, argument):",
                "    parts = argument.split()",
                "    if len(parts) != 2:",
                "        connection.sendall(b'ERR bad-request\\n')",
                "        return",
                "    try:",
                "        vendor_id, product_id = parse_device_id(",
                "            '%s:%s' % (parts[0], parts[1]))",
                "    except CliError:",
                "        connection.sendall(b'ERR bad-request\\n')",
                "        return",
                "    try:",
                "        fd = device_fd(vendor_id, product_id)",
                "    except BridgeError as error:",
                "        connection.sendall(('ERR %s\\n' % error).encode('ascii'))",
                "        return",
                "    except (CliError, OSError, ValueError):",
                "        connection.sendall(b'ERR usb-open-failed\\n')",
                "        return",
                "    message = ('OK %04x %04x\\n' % (vendor_id, product_id)).encode('ascii')",
                "    connection.sendmsg(",
                "        [message],",
                "        [(socket.SOL_SOCKET, socket.SCM_RIGHTS,",
                "          array.array('i', [fd]))])",
                "    # The client owns the descriptor now; the app-side connection",
                "    # keeps the device open until the next usb.open replaces it.",
                "    os.close(fd)",
                "",
                "",
                "def handle_connection(connection):",
                "    try:",
                "        with connection:",
                "            connection.settimeout(BRIDGE_TIMEOUT_SECONDS)",
                "            raw = bytearray()",
                "            while len(raw) < MAX_REQUEST_BYTES:",
                "                chunk = connection.recv(MAX_REQUEST_BYTES)",
                "                if not chunk:",
                "                    break",
                "                raw.extend(chunk)",
                "                if bytes([10]) in raw:",
                "                    break",
                "            line = raw.split(bytes([10]), 1)[0].decode('ascii',",
                "                                                        'replace').strip()",
                "            if line == 'LIST':",
                "                handle_list(connection)",
                "            elif line.startswith('OPEN '):",
                "                handle_open(connection, line[len('OPEN '):])",
                "            elif line == 'PING':",
                "                connection.sendall(b'PONG\\n')",
                "            else:",
                "                connection.sendall(b'ERR bad-request\\n')",
                "    except (CliError, BridgeError, OSError, ValueError):",
                "        pass",
                "",
                "",
                "def serve():",
                "    listener = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)",
                "    listener.bind('\\0' + SOCKET_NAME)",
                "    listener.listen(8)",
                "    listener.settimeout(1.0)",
                "    while True:",
                "        try:",
                "            connection, _ = listener.accept()",
                "        except socket.timeout:",
                "            continue",
                "        except OSError:",
                "            continue",
                "        worker = threading.Thread(target=handle_connection,",
                "                                  args=(connection,), daemon=True)",
                "        worker.start()",
                "",
                "",
                "def can_connect():",
                "    probe = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)",
                "    try:",
                "        probe.settimeout(1.0)",
                "        probe.connect('\\0' + SOCKET_NAME)",
                "        return True",
                "    except OSError:",
                "        return False",
                "    finally:",
                "        probe.close()",
                "",
                "",
                "def ensure():",
                "    if can_connect():",
                "        return 0",
                "    if os.fork() != 0:",
                "        for _ in range(20):",
                "            time.sleep(0.1)",
                "            if can_connect():",
                "                return 0",
                "        return 1",
                "    os.setsid()",
                "    devnull = os.open(os.devnull, os.O_RDWR)",
                "    for target in (0, 1, 2):",
                "        os.dup2(devnull, target)",
                "    serve()",
                "    os._exit(0)",
                "",
                "",
                "def main(argv):",
                "    if argv and argv[0] == '--ensure':",
                "        return ensure()",
                "    serve()",
                "    return 0",
                "",
                "",
                "if __name__ == '__main__':",
                "    sys.exit(main(sys.argv[1:]))",
                "") + "\n";
    }
}
