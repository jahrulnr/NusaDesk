    /**
     * The exact shell wrapper installed at {@link #WRAPPER_GUEST_PATH}.
     * It shadows {@code /usr/bin/adb} on PATH, lazily compiles the shim,
     * ensures the daemon is listening, and execs the real adb with the
     * shim preloaded — falling back to the plain adb whenever the shim,
     * the compiler, or the bridge is unavailable, which is what makes the
     * shadowing safe.
     *
     * @param appVersion app version stamped into the script header
     */
    public static String adbWrapperContent(String appVersion) {
        String version = GuestAwarenessReadmeWriter.requireVersionForWriter(appVersion);
        return String.join("\n",
                "#!/bin/sh",
                "# NusaDesk adb USB shim wrapper - generated by the NusaDesk Android",
                "# app. App version: " + version,
                "# Installed as /usr/local/bin/adb so it shadows the stock",
                "# /usr/bin/adb on PATH. It lazily builds the libusb shim, makes",
                "# sure nusadesk-usbd is listening, and execs the real adb with",
                "# ADB_LIBUSB=1 and the shim preloaded. Any missing piece falls",
                "# back to the plain adb, so shadowing can never break it.",
                "SHIM_DIR=/opt/nusadesk",
                "SHIM=\"$SHIM_DIR/libusb-shim.so\"",
                "SRC=\"$SHIM_DIR/libusb-shim.c\"",
                "DAEMON=/usr/local/bin/nusadesk-usbd",
                "REAL_ADB=/usr/bin/adb",
                "if [ -r /run/nusadesk/android-bridge.env ] && [ -r \"$SRC\" ]; then",
                "    if [ ! -r \"$SHIM\" ] && command -v gcc >/dev/null 2>&1; then",
                "        gcc -O2 -fPIC -shared -o \"$SHIM\" \"$SRC\" -ldl 2>/dev/null || rm -f \"$SHIM\"",
                "    fi",
                "    if [ -r \"$SHIM\" ]; then",
                "        [ -r \"$DAEMON\" ] && python3 \"$DAEMON\" --ensure >/dev/null 2>&1",
                "        exec env ADB_LIBUSB=1 LD_LIBRARY_PATH=\"/opt/nusadesk/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}\" LD_PRELOAD=\"$SHIM${LD_PRELOAD:+:$LD_PRELOAD}\" \"$REAL_ADB\" \"$@\"",
                "    fi",
                "fi",
                "exec \"$REAL_ADB\" \"$@\"",
                "") + "\n";
    }
