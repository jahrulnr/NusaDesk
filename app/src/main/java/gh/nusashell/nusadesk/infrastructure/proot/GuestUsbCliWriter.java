package gh.nusashell.nusadesk.infrastructure.proot;

/**
 * Guest-side USB pass-through CLI.
 *
 * <p>The guest runs under PRoot and has no direct view of Android's USB
 * devices. For the USB pass-through capability the app owns the Android
 * half: it lists the attached devices, requests USB permission when the
 * platform requires it, opens the device, and hands the opened file
 * descriptor to the guest over an abstract unix socket with
 * {@code SCM_RIGHTS}. This writer installs
 * {@code /usr/local/bin/nusadesk-usb}, the guest half of that contract:</p>
 *
 * <ul>
 *   <li>{@code nusadesk-usb list} prints the {@code usb.list} inventory as
 *       {@code VID:PID  name  manufacturer product} rows plus a count;</li>
 *   <li>{@code nusadesk-usb probe VID:PID} runs the full open sequence and
 *       proves the received fd is the requested device by reading its
 *       descriptor through a {@code USBDEVFS_CONTROL} ioctl;</li>
 *   <li>{@code nusadesk-usb exec VID:PID -- cmd ...} opens the device the
 *       same way and runs the command with the fd exported as
 *       {@code NUSADESK_USB_FD}.</li>
 * </ul>
 *
 * <p>The script speaks the same authenticated loopback JSON protocol as
 * {@code nusadesk-android}: same session env file, same envelope, typed
 * errors. It runs no shell — {@code exec} spawns the command directly —
 * never accepts a user-supplied method name, and never prints the session
 * token. Like every generated guest file it is rewritten by
 * {@link GuestAwarenessReadmeWriter#ensure} on session start, so an app
 * update replaces a stale copy.</p>
 */
public final class GuestUsbCliWriter {

    /** Guest-relative CLI path, executable on PATH. */
    public static final String GUEST_CLI_RELATIVE_PATH = "usr/local/bin/nusadesk-usb";
    /** CLI file name inside the fixed bin parent. */
    public static final String CLI_FILE_NAME = "nusadesk-usb";

    private GuestUsbCliWriter() {
    }

    /**
     * The exact executable Python 3 script installed at
     * {@link #GUEST_CLI_RELATIVE_PATH}. Public so tests and documentation
     * tooling can pin the generated text.
     *
     * @param appVersion app version stamped into the script header
     */
    public static String scriptContent(String appVersion) {
        String version = GuestAwarenessReadmeWriter.requireVersionForWriter(appVersion);
        return String.join("\n",
                "#!/usr/bin/env python3",
                "# NusaDesk USB pass-through CLI - generated by the NusaDesk Android",
                "# app. App version: " + version,
                "# Fixed session env: " + GuestAwarenessReadmeWriter.GUEST_ENV_FILE_PATH,
                "# This tool issues only the usb.list and usb.open bridge methods.",
                "# It never runs a shell, never takes a user-supplied method name,",
                "# and never prints the session token. usb.open makes the app",
                "# connect back to the abstract unix listener below and pass the",
                "# opened device fd with SCM_RIGHTS; exec then hands that fd to the",
                "# child process.",
                "",
                "import array",
                "import ctypes",
                "import json",
                "import os",
                "import secrets",
                "import socket",
                "import struct",
                "import subprocess",
                "import sys",
                "",
                "ENV_FILE = '" + GuestAwarenessReadmeWriter.GUEST_ENV_FILE_PATH + "'",
                "SOCKET_TIMEOUT_SECONDS = 15.0",
                "# usb.open can block inside the app while the USB permission",
                "# dialog is up, so it gets a wider timeout than a plain query.",
                "USB_OPEN_TIMEOUT_SECONDS = 75.0",
                "LISTEN_TIMEOUT_SECONDS = 60.0",
                "MAX_CONFIG_LINE_BYTES = 1024",
                "MAX_RESPONSE_BYTES = 16384",
                "PROTOCOL_VERSION = 1",
                "ENV_ADDRESS = 'NUSADESK_ANDROID_BRIDGE_ADDRESS'",
                "ENV_PORT = 'NUSADESK_ANDROID_BRIDGE_PORT'",
                "ENV_TOKEN = 'NUSADESK_ANDROID_BRIDGE_TOKEN'",
                "ENV_PROTOCOL = 'NUSADESK_ANDROID_BRIDGE_PROTOCOL'",
                "TOKEN_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-'",
                "SOCKET_PREFIX = 'nu-usb-'",
                "FD_ENV = 'NUSADESK_USB_FD'",
                "# USBDEVFS_CONTROL = _IOWR('U', 0, struct usbdevfs_ctrltransfer)",
                "USBDEVFS_CONTROL = 0xC0185500",
                "DESCRIPTOR_SIZE = 18",
                "CONTROL_TIMEOUT_MS = 2000",
                "USAGE = ('usage: nusadesk-usb list'",
                "         + ' | probe <vendorId>:<productId>'",
                "         + ' | exec <vendorId>:<productId> -- <command> [args...]')",
                "",
                "",
                "class CliError(Exception):",
                "    pass",
                "",
                "",
                "class BridgeError(Exception):",
                "    pass",
                "",
                "",
                "class UsbdevfsCtrlTransfer(ctypes.Structure):",
                "    _fields_ = [('bRequestType', ctypes.c_ubyte),",
                "                ('bRequest', ctypes.c_ubyte),",
                "                ('wValue', ctypes.c_ushort),",
                "                ('wIndex', ctypes.c_ushort),",
                "                ('wLength', ctypes.c_ushort),",
                "                ('timeout', ctypes.c_uint),",
                "                ('data', ctypes.c_void_p)]",
                "",
                "",
                "def load_config(path):",
                "    values = {}",
                "    try:",
                "        with open(path, 'r', encoding='ascii') as handle:",
                "            for raw in handle:",
                "                if len(raw) > MAX_CONFIG_LINE_BYTES:",
                "                    raise CliError('session env line too long')",
                "                line = raw.strip()",
                "                if not line or line.startswith('#'):",
                "                    continue",
                "                if '=' not in line:",
                "                    raise CliError('malformed session env line')",
                "                key, _, value = line.partition('=')",
                "                key = key.strip()",
                "                value = value.strip()",
                "                if key not in (ENV_ADDRESS, ENV_PORT, ENV_TOKEN,",
                "                                ENV_PROTOCOL):",
                "                    raise CliError('unexpected session env key')",
                "                if key in values:",
                "                    raise CliError('duplicate session env key')",
                "                values[key] = value",
                "    except (IOError, UnicodeDecodeError, CliError) as error:",
                "        if isinstance(error, CliError):",
                "            raise",
                "        raise CliError('cannot read session env')",
                "    address = values.get(ENV_ADDRESS)",
                "    port_text = values.get(ENV_PORT)",
                "    token = values.get(ENV_TOKEN)",
                "    protocol = values.get(ENV_PROTOCOL)",
                "    if address != '127.0.0.1':",
                "        raise CliError('bridge address must be loopback only')",
                "    if protocol != str(PROTOCOL_VERSION):",
                "        raise CliError('unsupported bridge protocol version')",
                "    try:",
                "        port = int(port_text, 10)",
                "    except (TypeError, ValueError):",
                "        raise CliError('invalid session env port')",
                "    if port < 1 or port > 65535:",
                "        raise CliError('invalid session env port')",
                "    if token is None or len(token) < 16 or len(token) > 256:",
                "        raise CliError('invalid session env token')",
                "    if any(ch not in TOKEN_ALPHABET for ch in token):",
                "        raise CliError('invalid session env token')",
                "    return address, port, token",
                "",
                "",
                "def build_request(method, token, params):",
                "    request = {",
                "        'v': PROTOCOL_VERSION,",
                "        'id': secrets.token_urlsafe(8),",
                "        'token': token,",
                "        'method': method,",
                "    }",
                "    if params is not None:",
                "        request['params'] = params",
                "    return json.dumps(request, separators=(',', ':'),",
                "                      ensure_ascii=True)",
                "",
                "",
                "def call(method, params, timeout):",
                "    address, port, token = load_config(ENV_FILE)",
                "    payload = build_request(method, token, params)",
                "    with socket.create_connection((address, port),",
                "                                  timeout=timeout) as sock:",
                "        sock.settimeout(timeout)",
                "        sock.sendall(payload.encode('ascii') + bytes([10]))",
                "        outgoing = bytearray()",
                "        while True:",
                "            chunk = sock.recv(4096)",
                "            if not chunk:",
                "                break",
                "            outgoing.extend(chunk)",
                "            if 10 in outgoing:",
                "                break",
                "            if len(outgoing) > MAX_RESPONSE_BYTES:",
                "                raise CliError('response too large')",
                "    if not outgoing:",
                "        raise CliError('empty bridge response')",
                "    line = outgoing.split(bytes([10]), 1)[0]",
                "    if len(line) > MAX_RESPONSE_BYTES:",
                "        raise CliError('response too large')",
                "    try:",
                "        parsed = json.loads(line.decode('utf-8'))",
                "    except ValueError:",
                "        raise CliError('bridge response is not JSON')",
                "    if not isinstance(parsed, dict):",
                "        raise CliError('bridge response is not a JSON object')",
                "    if parsed.get('v') != PROTOCOL_VERSION:",
                "        raise CliError('unsupported bridge response version')",
                "    if not parsed.get('ok'):",
                "        raise BridgeError(str(parsed.get('error', 'bridge error')))",
                "    return parsed",
                "",
                "",
                "def parse_device_id(text):",
                "    parts = text.split(':')",
                "    if len(parts) != 2:",
                "        raise CliError(USAGE)",
                "    pair = []",
                "    for part in parts:",
                "        try:",
                "            value = int(part, 16)",
                "        except ValueError:",
                "            raise CliError(USAGE)",
                "        if value < 0 or value > 0xffff:",
                "            raise CliError(USAGE)",
                "        pair.append(value)",
                "    return pair",
                "",
                "",
                "def open_device(vendor_id, product_id):",
                "    # The app connects back to this abstract-namespace listener while",
                "    # it answers usb.open and passes the opened device fd with",
                "    # SCM_RIGHTS.",
                "    name = SOCKET_PREFIX + secrets.token_hex(6)",
                "    listener = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)",
                "    try:",
                "        listener.bind('\\0' + name)",
                "        listener.listen(1)",
                "        listener.settimeout(LISTEN_TIMEOUT_SECONDS)",
                "        call('usb.open', {'vendorId': vendor_id,",
                "                          'productId': product_id,",
                "                          'socket': name}, USB_OPEN_TIMEOUT_SECONDS)",
                "        connection, _ = listener.accept()",
                "        connection.settimeout(LISTEN_TIMEOUT_SECONDS)",
                "    finally:",
                "        listener.close()",
                "    try:",
                "        return receive_fd(connection)",
                "    finally:",
                "        connection.close()",
                "",
                "",
                "def receive_fd(connection):",
                "    fds = array.array('i')",
                "    _msg, ancdata, _flags, _addr = connection.recvmsg(",
                "        4096, socket.CMSG_SPACE(fds.itemsize))",
                "    for level, ctype, cdata in ancdata:",
                "        if level == socket.SOL_SOCKET and ctype == socket.SCM_RIGHTS:",
                "            usable = len(cdata) - (len(cdata) % fds.itemsize)",
                "            fds.frombytes(cdata[:usable])",
                "    if not fds:",
                "        raise CliError('bridge sent no device fd')",
                "    return fds[0]",
                "",
                "",
                "def read_descriptor(fd):",
                "    # GET_DESCRIPTOR(DEVICE) through USBDEVFS_CONTROL.",
                "    payload = ctypes.create_string_buffer(DESCRIPTOR_SIZE)",
                "    transfer = UsbdevfsCtrlTransfer(",
                "        0x80, 6, 0x0100, 0, DESCRIPTOR_SIZE, CONTROL_TIMEOUT_MS,",
                "        ctypes.addressof(payload))",
                "    result = ctypes.CDLL(None, use_errno=True).ioctl(",
                "        fd, USBDEVFS_CONTROL, ctypes.byref(transfer))",
                "    if result < 0:",
                "        raise CliError('USBDEVFS_CONTROL failed: '",
                "                       + os.strerror(ctypes.get_errno()))",
                "    return payload.raw",
                "",
                "",
                "def cmd_list():",
                "    parsed = call('usb.list', None, SOCKET_TIMEOUT_SECONDS)",
                "    rows = parsed.get('devices')",
                "    if not isinstance(rows, str):",
                "        raise CliError('malformed bridge response')",
                "    try:",
                "        devices = json.loads(rows)",
                "    except ValueError:",
                "        raise CliError('malformed bridge response')",
                "    if not isinstance(devices, list):",
                "        raise CliError('malformed bridge response')",
                "    for device in devices:",
                "        line = ['%04x:%04x' % (device['vendorId'],",
                "                               device['productId'])]",
                "        for key in ('name', 'manufacturer', 'product'):",
                "            if device.get(key) is not None:",
                "                line.append(str(device[key]))",
                "        print('  '.join(line))",
                "    count = parsed.get('count')",
                "    if not isinstance(count, int):",
                "        raise CliError('malformed bridge response')",
                "    print('count: ' + str(count))",
                "    return 0",
                "",
                "",
                "def cmd_probe(vendor_id, product_id):",
                "    fd = open_device(vendor_id, product_id)",
                "    try:",
                "        descriptor = read_descriptor(fd)",
                "    finally:",
                "        os.close(fd)",
                "    bcd_usb = struct.unpack_from('<H', descriptor, 2)[0]",
                "    id_vendor = struct.unpack_from('<H', descriptor, 8)[0]",
                "    id_product = struct.unpack_from('<H', descriptor, 10)[0]",
                "    if id_vendor != vendor_id or id_product != product_id:",
                "        print('nusadesk-usb: descriptor id mismatch: requested '",
                "              + '%04x:%04x but the device reports %04x:%04x'",
                "              % (vendor_id, product_id, id_vendor, id_product),",
                "              file=sys.stderr)",
                "        return 1",
                "    print('probe ok: idVendor=%04x idProduct=%04x bcdUSB=0x%04x'",
                "          % (id_vendor, id_product, bcd_usb))",
                "    return 0",
                "",
                "",
                "def cmd_exec(vendor_id, product_id, command):",
                "    fd = open_device(vendor_id, product_id)",
                "    try:",
                "        completed = subprocess.run(",
                "            command, env={**os.environ, FD_ENV: str(fd)},",
                "            pass_fds=(fd,))",
                "    finally:",
                "        os.close(fd)",
                "    return completed.returncode",
                "",
                "",
                "def main(argv):",
                "    if len(argv) == 1 and argv[0] in ('-h', '--help'):",
                "        print(USAGE)",
                "        return 0",
                "    try:",
                "        if not argv:",
                "            raise CliError(USAGE)",
                "        if argv[0] == 'list':",
                "            if len(argv) != 1:",
                "                raise CliError(USAGE)",
                "            return cmd_list()",
                "        if argv[0] == 'probe':",
                "            if len(argv) != 2:",
                "                raise CliError(USAGE)",
                "            vendor_id, product_id = parse_device_id(argv[1])",
                "            return cmd_probe(vendor_id, product_id)",
                "        if argv[0] == 'exec':",
                "            if len(argv) < 4 or argv[2] != '--':",
                "                raise CliError(USAGE)",
                "            vendor_id, product_id = parse_device_id(argv[1])",
                "            return cmd_exec(vendor_id, product_id, argv[3:])",
                "        raise CliError(USAGE)",
                "    except (CliError, BridgeError) as error:",
                "        print('nusadesk-usb: ' + str(error), file=sys.stderr)",
                "        return 1",
                "    except (ValueError, TypeError, KeyError):",
                "        # A malformed bridge payload is a protocol fault, not a typed",
                "        # capability error.",
                "        print('nusadesk-usb: malformed bridge response',",
                "              file=sys.stderr)",
                "        return 1",
                "    except OSError as error:",
                "        print('nusadesk-usb: ' + str(error), file=sys.stderr)",
                "        return 1",
                "",
                "",
                "if __name__ == '__main__':",
                "    sys.exit(main(sys.argv[1:]))",
                "") + "\n";
    }
}
